// Failure after create_market: does the log offer a reset that could re-create the market?
import { chromium } from '@playwright/test'
const base = process.argv[2] ?? 'http://localhost:3001'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('pageerror', e.message))
await page.goto(base + '/new?draft=draft-bkt41q', { waitUntil: 'domcontentloaded' })
await page.waitForSelector('#sec-review', { timeout: 30000 })
await page.getByRole('button', { name: /Connect wallet to publish/ }).click().catch(() => {})
await page.evaluate(() => document.getElementById('sec-review')?.scrollIntoView({ block: 'start' }))
await page.locator('#ack').check()
await page.getByRole('button', { name: 'Publish claim and create market' }).click()
await page.waitForSelector('text=terms frozen', { timeout: 60000 })
await page.getByRole('button', { name: /Simulate failure on next transaction/ }).first().click()
await page.waitForSelector('text=Retry step', { timeout: 60000 })
await page.evaluate(() => document.querySelector('#sec-review [aria-live="polite"]')?.scrollIntoView({ block: 'center' }))
await page.waitForTimeout(300)
await page.screenshot({ path: '.qa/peek/fail-after-freeze.png' })
const reset = page.getByRole('button', { name: 'Reset log' }).first()
console.log('reset visible:', await reset.isVisible().catch(() => false))
if (await reset.isVisible().catch(() => false)) {
  await reset.click()
  await page.waitForTimeout(800)
  await page.evaluate(() => document.getElementById('sec-review')?.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: '.qa/peek/after-reset.png' })
  const txt = await page.locator('#sec-review').innerText()
  console.log('after reset — publish button:', /Publish claim and create market/.test(txt), 'frozen note:', /read-only|frozen/i.test(txt))
}
const claimId = await page.evaluate(() => document.body.innerText.match(/id (pine-[a-z0-9]+)/)?.[1])
console.log('claim id', claimId)
if (claimId) {
  await page.goto(base + '/claims/' + claimId, { waitUntil: 'domcontentloaded' })
  await page.waitForTimeout(2500)
  await page.screenshot({ path: '.qa/peek/fail-after-freeze-claim.png' })
  const t = await page.locator('main').innerText()
  console.log('claim page: finish publishing panel =', /Finish publishing/.test(t), ' not found =', /No claim with id/.test(t))
}
await page.goto(base + '/drafts', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2000)
await page.screenshot({ path: '.qa/peek/fail-after-freeze-drafts.png', fullPage: true })
console.log('drafts lists in-progress publication:', /Token bucket/.test(await page.locator('main').innerText()))
await browser.close()
