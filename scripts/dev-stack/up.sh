# ------------------------------------------------------------------------------------------------ indexer + API dev server
start_service() {
  # $1 name, $2 cwd, $3 port that must be free, rest: command
  local name=$1 cwd=$2 port=$3
  shift 3
  port_busy "$port" && die "port $port is in use by a process up.sh did not start (needed by $name)"
  node "$DEV_STACK_DIR/spawn-detached.mjs" "$cwd" "$LOG_DIR/$name.log" "$PID_DIR/$name.pid" -- "$@"
  log "$name: started (pid $(service_pid "$name" || echo '?'), log $LOG_DIR/$name.log)"
}

wait_http() {
  # $1 name, $2 url, $3 seconds
  local name=$1 url=$2 seconds=$3
  for _ in $(seq 1 $((seconds * 2))); do
    [ "$(curl -s -o /dev/null -w '%{http_code}' -m 3 "$url" || true)" = "200" ] && return 0
    service_pid "$name" >/dev/null || die "$name exited (see $LOG_DIR/$name.log)"
    sleep 0.5
  done
  die "$name did not become ready at $url within ${seconds}s (see $LOG_DIR/$name.log)"
}

